RESOLVED = {(lang, address): resolve(table, address) for lang, table in TEXTS.items() for address in ("f", "m", "x")}


def texts(lang, address="x"):
    return RESOLVED.get((lang, address if address in ("f", "m", "x") else "x"), RESOLVED[("he", "x")])
